def _write(name: str, dry: bool) -> list[dict]:
    root = paths.repo_root()
    rows = []
    for rel, text in reg.discover().generators[name].render().items():
        f = root / rel
        old = f.read_text(encoding="utf-8") if f.exists() else None
        rows.append({"name": rel, "status": "unchanged" if old == text else ("would write" if dry else "written"), "was": "missing" if old is None else "present"})
        if not dry and old != text:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(text, encoding="utf-8")
    return rows


