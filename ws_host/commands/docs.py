def stale() -> list[dict]:
    """Each generator's files compared with what its code writes now (0041 FR-036)."""
    root = paths.repo_root()
    out = []
    for name, g in sorted(reg.discover().generators.items()):
        files = []
        for rel, text in g.render().items():
            f = root / rel
            have = f.read_text(encoding="utf-8") if f.exists() else None
            files.append({"name": rel, "status": "current" if have == text else ("missing" if have is None else "stale")})
        bad = [f for f in files if f["status"] != "current"]
        out.append({"name": name, "status": "fail" if bad else "ok", "command": g.command, "files": files,
                    "plain": f"{name}: " + (f"{len(bad)} file(s) out of date; run {NAME} {g.command}" if bad else f"{len(files)} file(s) current")})
    return out


@command("fresh", category="check", summary="Prove the generated files are current",
         args=(Arg("generators", "STRING", positional=True, multiple=True),))
def fresh(ctx, generators):
    rows = [r for r in stale() if not generators or r["name"] in generators]
    if generators and len(rows) != len(set(generators)):
        raise WsError("usage", "no such generator", f"I do not know a generator called one of those. They are: {', '.join(sorted(reg.discover().generators))}.", exit_code=2)
    bad = [r for r in rows if r["status"] == "fail"]
    return Resource("fresh", "generators", {"plain": "Every generated file is current." if not bad else
                                            f"{len(bad)} generated file set{'s' if len(bad) != 1 else ''} out of date; the commands below rewrite them.",
                                            "generators": rows},
                    actions=[Action(tuple(b["command"].split()), f"Rewrite {b['name']}") for b in bad], status=FAILED if bad else OK)


