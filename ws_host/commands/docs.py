def header(kind: str, name: str, command_: str) -> str:
    text = f"Generated by {NAME}: {name}. Rewrite it with `{NAME} {command_}`; do not edit it by hand."
    return f"// {text}\n" if kind == "adoc" else f"<!-- {text} -->\n"


def _cell(s) -> str:
    return str(s).replace("|", "\\|")


