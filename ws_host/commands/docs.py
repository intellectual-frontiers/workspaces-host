def _block(text: str) -> str:
    """Indented lines in a topic are commands: they become listing blocks."""
    out, code = [], []
    for ln in text.split("\n"):
        if ln.startswith("    "):
            code.append(ln[4:])
            continue
        if code:
            out += ["----", *code, "----"]
            code = []
        out.append(ln)
    if code:
        out += ["----", *code, "----"]
    return "\n".join(out)


